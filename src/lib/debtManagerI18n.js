export function debtText(language, source, values = {}) {
  if (typeof source !== 'string') return '';
  const template = isEnglishLanguage(language) ? (english[source] || source) : source;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(values[key] ?? ''));
}

export function debtErrorText(language, source) {
  if (!isEnglishLanguage(language)) return source;
  // Provider errors may contain backend diagnostics; never show them as untranslated UI.
  return english[source] || 'Unable to complete this action. Reload the records and try again.';
}
