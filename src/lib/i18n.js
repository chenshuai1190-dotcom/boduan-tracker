export const LANGUAGE_STORAGE_KEY = 'xmoney_language';
export const DEFAULT_LANGUAGE = 'zh';
export const SUPPORTED_LANGUAGES = ['zh', 'en'];

export function normalizeLanguage(value) {
  const raw = String(value || '').trim().toLowerCase();
  return SUPPORTED_LANGUAGES.includes(raw) ? raw : DEFAULT_LANGUAGE;
}

export function getStoredLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function saveStoredLanguage(language) {
  const normalized = normalizeLanguage(language);
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
  } catch {}
  return normalized;
}

export function isEnglishLanguage(language) {
  return normalizeLanguage(language) === 'en';
}

