#!/usr/bin/env node

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const rootDir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const stableDir = path.join(os.homedir(), '.config', 'boduan-tracker');
const stableLocalEnv = path.join(stableDir, 'local.env');
const stableEodhdEnv = path.join(stableDir, 'eodhd.env');
const worktreeEnv = path.join(rootDir, '.env.local');
const force = process.argv.includes('--force');

const MANAGED_KEYS = [
  'VITE_SUPABASE_URL',
  'VITE_SUPABASE_ANON_KEY',
  'EODHD_API_KEY',
  'QUOTE_API_AUTH_REQUIRED',
  'QUOTE_ALLOWED_ORIGINS',
];
const FORBIDDEN_KEYS = [
  'VITE_EODHD_TOKEN',
  'VITE_SUPABASE_SERVICE_ROLE_KEY',
  'VITE_CRON_SECRET',
];

const failures = [];
const summary = [];

function readEnvFile(file) {
  const env = {};
  if (!fs.existsSync(file)) return env;
  const content = fs.readFileSync(file, 'utf8');
  for (const line of content.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    env[match[1]] = value;
  }
  return env;
}

function displayPath(file) {
  return file.replace(os.homedir(), '~');
}

function mode(file) {
  return (fs.statSync(file).mode & 0o777).toString(8);
}

function assertPrivateFile(file, label) {
  if (!fs.existsSync(file)) {
    failures.push(`${label} missing: ${displayPath(file)}`);
    return;
  }
  const actualMode = mode(file);
  summary.push(`${label}=${displayPath(file)} mode=${actualMode}`);
  if ((fs.statSync(file).mode & 0o077) !== 0) {
    failures.push(`${label} should not be group/world-readable: ${displayPath(file)}`);
  }
}

function assertNoForbiddenKeys(env, label) {
  for (const key of FORBIDDEN_KEYS) {
    if (Object.prototype.hasOwnProperty.call(env, key)) {
      failures.push(`${label} must not define ${key}`);
    }
  }
}

function serializeEnv(env) {
  return [
    '# Generated by npm run bootstrap:local-env.',
    '# Local-only file. Do not commit or print values.',
    ...Object.keys(env)
      .sort()
      .map((key) => `${key}=${env[key]}`),
    '',
  ].join('\n');
}

assertPrivateFile(stableLocalEnv, 'stableLocalEnv');
assertPrivateFile(stableEodhdEnv, 'stableEodhdEnv');

const stableLocal = readEnvFile(stableLocalEnv);
const stableEodhd = readEnvFile(stableEodhdEnv);
const existing = readEnvFile(worktreeEnv);

assertNoForbiddenKeys(stableLocal, 'stableLocalEnv');
assertNoForbiddenKeys(stableEodhd, 'stableEodhdEnv');
assertNoForbiddenKeys(existing, 'worktreeEnv');

const source = {
  ...stableLocal,
  EODHD_API_KEY: stableEodhd.EODHD_API_KEY || stableLocal.EODHD_API_KEY,
};

for (const key of ['VITE_SUPABASE_URL', 'VITE_SUPABASE_ANON_KEY', 'EODHD_API_KEY']) {
  if (!String(source[key] || '').trim()) {
    failures.push(`stable local config missing required key: ${key}`);
  }
}

if (failures.length === 0) {
  const merged = { ...existing };
  const written = [];
  const skipped = [];
  for (const key of MANAGED_KEYS) {
    const value = String(source[key] || '').trim();
    if (!value) continue;
    if (!force && String(merged[key] || '').trim()) {
      skipped.push(key);
      continue;
    }
    merged[key] = value;
    written.push(key);
  }
  fs.writeFileSync(worktreeEnv, serializeEnv(merged), { mode: 0o600 });
  fs.chmodSync(worktreeEnv, 0o600);
  summary.push(`worktreeEnv=.env.local mode=${mode(worktreeEnv)}`);
  summary.push(`managedKeysWritten=${written.length > 0 ? written.join(',') : 'none'}`);
  if (skipped.length > 0) summary.push(`existingKeysPreserved=${skipped.join(',')}`);
}

if (failures.length > 0) {
  console.error('bootstrap local env: FAIL');
  for (const item of summary) console.error(`- ${item}`);
  for (const item of failures) console.error(`ERROR: ${item}`);
  process.exit(1);
}

console.log('bootstrap local env: PASS');
for (const item of summary) console.log(`- ${item}`);
