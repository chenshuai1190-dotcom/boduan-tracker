// Optional local PostgreSQL execution test. Reads no .env, credentials or user data.
// PGlite is installed outside the repo; this test never opens a database/network connection.
// Run: PGLITE_MODULE_FILE=/absolute/path/to/pglite/dist/index.js node --test tests/review-journal-migration.test.js
// auth.uid(), Storage tables and foldername() are fixtures. This checks SQL/RLS behavior,
// not Supabase Storage HTTP, signed URLs, MIME sniffing or concurrent connections.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';
import test from 'node:test';

const moduleFile = process.env.PGLITE_MODULE_FILE;
const USER_A = '11111111-1111-4111-8111-111111111111';
const USER_B = '22222222-2222-4222-8222-222222222222';
const OPERATION = '33333333-3333-4333-8333-333333333333';
const BUCKET = 'review-journal-images';

test('review migration runs in isolated PostgreSQL with legacy rows and account policies', {
  skip: !moduleFile && 'Set PGLITE_MODULE_FILE to a local PGlite install for SQL execution; no server is contacted.',
}, async t => {
  assert.ok(isAbsolute(moduleFile), 'PGLITE_MODULE_FILE must be an absolute local path');
  const { PGlite } = await import(pathToFileURL(moduleFile).href);
  const db = await PGlite.create();
  const migration = await readFile(new URL('../supabase/review-journal.sql', import.meta.url), 'utf8');
  const query = (sql, params = []) => db.query(sql, params);
  const rows = async (sql, params = []) => (await query(sql, params)).rows;
  const denied = (fn, code = '42501') => assert.rejects(fn, error => error.code === code);
  const tables = ['disciplines', 'review_logs'];
  const legacyIds = {};

  async function asUser(userId, sql, params = [], role = 'authenticated') {
    assert.ok(['authenticated', 'anon'].includes(role));
    await db.exec(`set role ${role}`);
    try {
      await query("select set_config('request.jwt.claim.sub', $1, false)", [userId || '']);
      return await rows(sql, params);
    } finally {
      await db.exec('reset role');
      await query("select set_config('request.jwt.claim.sub', '', false)");
    }
  }

  async function insertEntry(table, userId, metadata = {}) {
    const extra = table === 'review_logs' ? ", log_date" : '';
    const value = table === 'review_logs' ? ", '2026-11-06'" : '';
    return (await asUser(userId, `insert into public.${table}(user_id, text, review_data${extra})
      values ($1::uuid, 'fixture record', $2::jsonb${value}) returning *`, [userId, JSON.stringify(metadata)]))[0];
  }

  try {
    await db.exec(`
      create role anon nologin;
      create role authenticated nologin;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth to anon, authenticated;
      grant execute on function auth.uid() to anon, authenticated;

      -- Deliberately different primary-key types: the migration must retain both.
      create table public.disciplines (
        id bigint generated by default as identity primary key,
        user_id uuid not null, level text not null default '🟢', text text not null,
        pinned boolean not null default false, sort_order integer not null default 0,
        created_at timestamptz not null default now(), updated_at timestamptz not null default now()
      );
      create table public.review_logs (
        id uuid primary key default gen_random_uuid(), user_id uuid not null,
        log_date date not null, mood text not null default '', text text not null,
        created_at timestamptz not null default now(), updated_at timestamptz not null default now()
      );
      grant select, insert, update, delete on public.disciplines, public.review_logs to anon, authenticated;
      grant usage, select on all sequences in schema public to anon, authenticated;
      alter table public.disciplines enable row level security;
      alter table public.review_logs enable row level security;
      create policy "users can manage own disciplines" on public.disciplines for all to authenticated
        using (auth.uid() = user_id) with check (auth.uid() = user_id);
      create policy "users can manage own review logs" on public.review_logs for all to authenticated
        using (auth.uid() = user_id) with check (auth.uid() = user_id);

      -- Supabase Storage shape needed by the SQL, without the Storage service.
      create schema storage;
      create table storage.buckets (
        id text primary key, name text not null, public boolean not null default false,
        file_size_limit bigint, allowed_mime_types text[]
      );
      create table storage.objects (
        id uuid primary key default gen_random_uuid(),
        bucket_id text not null references storage.buckets(id), name text not null,
        unique (bucket_id, name)
      );
      create function storage.foldername(name text) returns text[] language sql immutable as
        $$ select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1] $$;
      alter table storage.objects enable row level security;
      grant usage on schema storage to anon, authenticated;
      grant execute on function storage.foldername(text) to anon, authenticated;
      grant select, insert, update, delete on storage.objects to anon, authenticated;
      insert into storage.buckets(id, name, public) values ('other-images', 'other-images', true);
    `);
    for (const table of tables) {
      const extra = table === 'review_logs' ? ", log_date, mood" : ', level, pinned, sort_order';
      const values = table === 'review_logs' ? ", '2026-11-01', '平静'" : ", '📣', true, 7";
      for (const userId of [USER_A, USER_B]) {
        const result = await rows(`insert into public.${table}(user_id, text, created_at, updated_at${extra})
          values ($1::uuid, 'legacy text', '2020-01-01', '2020-01-01'${values}) returning *`, [userId]);
        if (userId === USER_A) legacyIds[table] = result[0].id;
      }
    }
    const before = Object.fromEntries(await Promise.all(tables.map(async table => [table,
      await rows(`select * from public.${table} order by user_id`)])));

    await t.test('migration reapplies without moving old rows or changing primary-key types', async () => {
      await db.exec(migration);
      await db.exec(migration);
      for (const table of tables) {
        const after = await rows(`select * from public.${table} order by user_id`);
        assert.equal(after.length, before[table].length);
        after.forEach((row, index) => {
          const { review_data, review_revision, ...legacy } = row;
          assert.deepEqual(legacy, before[table][index]);
          assert.deepEqual(review_data, {});
          assert.equal(review_revision, 0);
        });
      }
      const idTypes = await rows("select table_name, data_type from information_schema.columns where table_schema='public' and table_name in ('disciplines','review_logs') and column_name='id' order by table_name");
      assert.deepEqual(idTypes, [{ table_name: 'disciplines', data_type: 'bigint' }, { table_name: 'review_logs', data_type: 'uuid' }]);
      const [bucket] = await rows('select * from storage.buckets where id=$1', [BUCKET]);
      assert.equal(bucket.public, false);
      assert.equal(Number(bucket.file_size_limit), 10485760);
      assert.deepEqual(bucket.allowed_mime_types, ['image/jpeg', 'image/png', 'image/webp']);
      assert.equal((await rows("select has_function_privilege('authenticated','public.bump_review_journal_revision()','EXECUTE') as allowed"))[0].allowed, false);
    });

    await t.test('legacy text updates execute the revoked trigger and advance revisions', async () => {
      for (const table of tables) {
        const [row] = await asUser(USER_A, `update public.${table} set text='legacy edit' where id=$1 returning *`, [legacyIds[table]]);
        assert.equal(row.review_revision, 1);
        assert.deepEqual(row.review_data, {});
        assert.ok(new Date(row.updated_at).getTime() > Date.parse('2020-01-01'));
      }
    });

    await t.test('revision CAS rejects stale edits/deletes and illegal revision jumps', async () => {
      for (const table of tables) {
        const [saved] = await asUser(USER_A, `update public.${table} set text='modern edit', review_revision=2
          where id=$1 and user_id=$2::uuid and review_revision=1 returning *`, [legacyIds[table], USER_A]);
        assert.equal(saved.review_revision, 2);
        assert.deepEqual(await asUser(USER_A, `update public.${table} set text='stale', review_revision=2
          where id=$1 and user_id=$2::uuid and review_revision=1 returning id`, [legacyIds[table], USER_A]), []);
        await denied(() => asUser(USER_A, `update public.${table} set review_revision=9 where id=$1`, [legacyIds[table]]), '23514');
        assert.deepEqual(await asUser(USER_A, `delete from public.${table} where id=$1 and review_revision=1 returning id`, [legacyIds[table]]), []);
        const disposable = await insertEntry(table, USER_A);
        assert.equal((await asUser(USER_A, `delete from public.${table} where id=$1 and user_id=$2::uuid and review_revision=0 returning id`, [disposable.id, USER_A])).length, 1);
      }
    });

    await t.test('operation identity is unique per account and type and cannot be removed by editing', async () => {
      for (const table of tables) {
        const entry = await insertEntry(table, USER_A, { operationId: OPERATION, stocks: ['NVDA'] });
        await denied(() => insertEntry(table, USER_A, { operationId: OPERATION }), '23505');
        assert.equal((await insertEntry(table, USER_B, { operationId: OPERATION })).user_id, USER_B);
        const [legacyEdit] = await asUser(USER_A, `update public.${table} set text='legacy text on rich record' where id=$1 returning *`, [entry.id]);
        assert.equal(legacyEdit.review_revision, 1);
        assert.deepEqual(legacyEdit.review_data, { operationId: OPERATION, stocks: ['NVDA'] });
        await denied(() => asUser(USER_A, `update public.${table} set review_data='{}'::jsonb where id=$1`, [entry.id]), '23514');
        await denied(() => asUser(USER_A, `update public.${table} set review_data=$2::jsonb where id=$1`,
          [entry.id, JSON.stringify({ operationId: USER_B })]), '23514');
      }
    });

    await t.test('record RLS isolates reads and all write directions for two users and anonymous access', async () => {
      for (const table of tables) {
        for (const userId of [USER_A, USER_B]) {
          const visible = await asUser(userId, `select * from public.${table}`);
          assert.ok(visible.length >= 2);
          assert.ok(visible.every(row => row.user_id === userId));
        }
        assert.deepEqual(await asUser(USER_B, `update public.${table} set text='foreign edit' where id=$1 returning id`, [legacyIds[table]]), []);
        assert.deepEqual(await asUser(USER_B, `delete from public.${table} where id=$1 returning id`, [legacyIds[table]]), []);
        await denied(() => asUser(USER_A, `update public.${table} set user_id=$2::uuid where id=$1`, [legacyIds[table], USER_B]));
        const extra = table === 'review_logs' ? ", log_date" : '';
        const value = table === 'review_logs' ? ", '2026-11-06'" : '';
        await denied(() => asUser(USER_A, `insert into public.${table}(user_id,text${extra}) values ($1::uuid,'foreign insert'${value})`, [USER_B]));
        assert.deepEqual(await asUser(null, `select * from public.${table}`, [], 'anon'), []);
        await denied(() => asUser(null, `insert into public.${table}(user_id,text${extra}) values ($1::uuid,'anonymous'${value})`, [USER_A], 'anon'));
      }
    });

    await t.test('Storage RLS allows only own single-level paths in the dedicated bucket', async () => {
      const pathA = `${USER_A}/${OPERATION}.jpg`;
      const pathB = `${USER_B}/${OPERATION}.jpg`;
      const insertObject = (userId, bucket, path, role) => asUser(userId,
        'insert into storage.objects(bucket_id,name) values($1,$2) returning name', [bucket, path], role);
      await insertObject(USER_A, BUCKET, pathA);
      await insertObject(USER_B, BUCKET, pathB);
      assert.deepEqual(await asUser(USER_A, 'select name from storage.objects'), [{ name: pathA }]);
      assert.deepEqual(await asUser(USER_B, 'select name from storage.objects'), [{ name: pathB }]);
      await denied(() => insertObject(USER_A, BUCKET, `${USER_B}/foreign.jpg`));
      await denied(() => insertObject(USER_A, BUCKET, `${USER_A}/nested/photo.jpg`));
      await denied(() => insertObject(USER_A, 'other-images', `${USER_A}/photo.jpg`));
      await denied(() => asUser(USER_A, 'update storage.objects set name=$2 where name=$1', [pathA, `${USER_B}/moved.jpg`]));
      assert.deepEqual(await asUser(USER_A, "update storage.objects set name='overwritten.jpg' where name=$1 returning name", [pathB]), []);
      assert.deepEqual(await asUser(USER_A, 'delete from storage.objects where name=$1 returning name', [pathB]), []);
      assert.deepEqual(await asUser(null, 'select name from storage.objects', [], 'anon'), []);
      await denied(() => insertObject(null, BUCKET, `${USER_A}/anonymous.jpg`, 'anon'));
      assert.deepEqual(await asUser(USER_A, 'delete from storage.objects where name=$1 returning name', [pathA]), [{ name: pathA }]);
      assert.deepEqual(await asUser(USER_B, 'select name from storage.objects'), [{ name: pathB }]);
    });

    await t.test('reapplying after use retains rich metadata and revisions', async () => {
      const snapshot = {};
      for (const table of tables) snapshot[table] = await rows(`select * from public.${table} order by id`);
      await db.exec(migration);
      for (const table of tables) assert.deepEqual(await rows(`select * from public.${table} order by id`), snapshot[table]);
      assert.equal((await rows("select count(*)::integer as count from pg_trigger where tgname in ('disciplines_review_revision','review_logs_review_revision')"))[0].count, 2);
    });

    await t.test('preflight warning is real: unrelated permissive policies require a separate audit', async () => {
      await db.exec('create policy unrelated_legacy_read on public.disciplines for select to authenticated using (true)');
      try {
        await db.exec(migration);
        const visible = await asUser(USER_A, 'select user_id from public.disciplines');
        assert.ok(visible.some(row => row.user_id === USER_B), 'a permissive existing policy is OR-combined, not overridden');
      } finally {
        await db.exec('drop policy unrelated_legacy_read on public.disciplines');
      }
    });
  } finally {
    await db.close();
  }
});
